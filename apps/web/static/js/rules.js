export function blindTable() {
  return el('table', {className: 'rules__table'}, [
    el('thead', {}, [
      el('tr', {}, [el('th', {text: '级别'}), el('th', {text: '小盲/大盲'}), el('th', {text: '生效手数'})]),
    ]),
    el(
      'tbody',
      {},
      BLIND_LEVELS.map((blinds, index) =>
        el('tr', {}, [
          el('td', {text: String(index + 1)}),
          el('td', {text: formatBlinds(blinds)}),
          el('td', {text: index === 0 ? '第 1 手起' : `第 ${index * 10 + 1} 手起`}),
        ]),
      ),
    ),
  ]);
}

export function renderRules(container) {
  const sections = RULE_SECTIONS.map((section) =>
    el('section', {className: 'rules__section'}, [
      el('h2', {text: section.title}),
      el('ul', {}, section.items.map((item) => el('li', {text: item}))),
    ]),
  );
  const rankings = el('section', {className: 'rules__section'}, [
    el('h2', {text: '牌型大小（从大到小）'}),
    el(
      'ol',
      {className: 'rules__rankings'},
      HAND_RANKINGS.map((hand) => el('li', {}, [el('strong', {text: hand.name}), el('span', {text: `　${hand.detail}`})])),
    ),
  ]);
  const blinds = el('section', {className: 'rules__section'}, [
    el('h2', {text: '盲注表'}),
    el('p', {text: '起始筹码 1,000，每 10 手升一级，最高 4,500/9,000。'}),
    blindTable(),
  ]);
  const faq = el('section', {className: 'rules__section'}, [
    el('h2', {text: '常见问题'}),
    ...RULES_FAQ.map((item) =>
      el('div', {className: 'rules__faq'}, [el('h3', {text: item.question}), el('p', {className: 'muted', text: item.answer})]),
    ),
  ]);
  render(container, [...sections, rankings, blinds, faq]);
}

if (typeof document !== 'undefined') {
  document.addEventListener('DOMContentLoaded', () => {
    const container = qs('#rules-content');
    if (container) renderRules(container);
  });
}
